"""Pages of the "Tensap tutorials", a subsection of the Use cases.

The original tutorials of tensap are kept, unchanged, as non-regression
scripts in ``test/non_regression_scripts/``. When the documentation is
built, this extension writes one page per script in ``doc/tutorials/`` (not
versioned): the script word for word, with a link to its version in the
Examples Gallery, which shows the outputs. The scripts are not executed here;
the tests run them.

The page of the Use cases lists the tutorials last in its table of contents
(after the use cases generated by sphinx-gallery, so that they come after
them in the navigation).

The link to the gallery is found in the docstring of the example, which says
"This example comes from the script ``test/non_regression_scripts/...``".
"""

import ast
import re
from pathlib import Path

OUT_DIR = "tutorials"
FOLDERS = {
    "tensor_algebra": "Tensor algebra",
    "functions": "Functions",
    "approximation": "Approximation",
    "poincare_learning": "Poincaré learning",
    "tools": "Tools",
}
ORIGIN = re.compile(r"``test/non_regression_scripts/([^`]+\.py)``")


def _gallery_links(repo):
    """Map each script to the label of its page in the gallery."""
    links = {}
    for path in sorted((repo / "examples").glob("*/*.py")):
        match = ORIGIN.search(path.read_text(encoding="utf-8"))
        if match:
            section, name = path.parent.name, path.stem
            links[match.group(1)] = f"sphx_glr_examples_{section}_{name}.py"
    return links


def _summary(path):
    """First sentence of the docstring of the script, if any."""
    try:
        doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")))
    except SyntaxError:
        return None
    if not doc:
        return None
    return " ".join(doc.split("\n\n")[0].split())


def _write(path, text):
    # Do not touch an unchanged page, so that Sphinx does not read it again.
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def generate(app):
    src = Path(app.srcdir)
    repo = src.parent
    scripts_dir = repo / "test" / "non_regression_scripts"
    out = src / OUT_DIR
    links = _gallery_links(repo)

    index = [
        ".. _tensap-tutorials:",
        "",
        "Tensap tutorials",
        "================",
        "",
        "The original tutorials of tensap, word for word, as they are in the",
        "repository (``test/non_regression_scripts/``, formerly ``tutorials/``).",
        "Each one is also in the :doc:`/examples/index`, split into commented",
        "steps, with its outputs and figures.",
        "",
    ]
    for folder, title in FOLDERS.items():
        scripts = sorted((scripts_dir / folder).glob("*.py"))
        if not scripts:
            continue
        index += [title, "-" * len(title), "", ".. toctree::", "   :maxdepth: 1", ""]
        for script in scripts:
            rel = f"{folder}/{script.name}"
            index.append(f"   {script.stem} <{folder}/{script.stem}>")
            lines = [script.name, "=" * len(script.name), ""]
            summary = _summary(script)
            if summary:
                lines += [summary, ""]
            lines += [f"Script ``test/non_regression_scripts/{rel}``."]
            if rel in links:
                lines[-1] += (
                    f" The same code, split into commented steps and with its"
                    f" outputs, is in the gallery: :ref:`{links[rel]}`."
                )
            depth = "../" * 3
            lines += [
                "",
                f".. literalinclude:: {depth}test/non_regression_scripts/{rel}",
                "   :language: python",
                "",
            ]
            _write(out / folder / f"{script.stem}.rst", "\n".join(lines))
        index.append("")
    _write(out / "index.rst", "\n".join(index))


def add_to_use_cases(app, docname, source):
    if docname == "use_cases/index":
        source[0] += "\n\n.. toctree::\n   :hidden:\n\n   /tutorials/index\n"


def setup(app):
    app.connect("builder-inited", generate)
    app.connect("source-read", add_to_use_cases)
    return {"parallel_read_safe": True, "parallel_write_safe": True}
